import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {resolve} from 'node:path';
const root=resolve(process.argv[2]);
const baseline=process.env.HIDI_CARE_BASE_SOURCE_SHA;
const old=path=>execFileSync('git',['show',baseline+':'+path],{cwd:root,encoding:'utf8'});
const appPath='apps/web/src/App.jsx',carePath='apps/web/src/components/BrandPromises.jsx';
const app=await readFile(root+'/'+appPath,'utf8');
assert.equal(app.replace("import './styles/care-break.css';\n",'').replace('            <BrandPromises />\n            <HidiEdit />','            <HidiEdit />\n            <BrandPromises />'),old(appPath),'Only the approved section order and CSS import change');
const care=await readFile(root+'/'+carePath,'utf8');
assert.equal(care.replace('promises-section section-space care-break','promises-section section-space'),old(carePath),'Care copy, icons, actions and links are retained');
assert.equal(await readFile(root+'/apps/web/src/styles/care-break.css','utf8'),await readFile(new URL('./care-break.css',import.meta.url),'utf8'));
console.log('PASS: care order and compact CSS match permanent source; existing care content and actions preserved');

import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
const root=resolve(process.argv[2]);
const require=createRequire(root+'/apps/web/package.json');
const {transform}=require('esbuild');
let source=await readFile(root+'/apps/web/src/components/HidiEdit.jsx','utf8');
source=source.replace(/^import .*;\n/gm,'').replace('export default function HidiEdit()', 'function HidiNextChapterComponent()');
const result=await transform(source,{loader:'jsx',jsx:'transform',jsxFactory:'React.createElement',jsxFragment:'React.Fragment',target:'es2020'});
const runtime=result.code.replaceAll('React.','HidiNextChapterReact.').replaceAll('useLandingMedia()','HidiNextChapterMedia()').replaceAll('landingImageProps(','HidiNextChapterImage(');
assert.equal(runtime,await readFile(new URL('./component.runtime.js',import.meta.url),'utf8'),'Runtime component exactly matches approved permanent source');
assert.equal(await readFile(root+'/apps/web/src/styles/next-chapter.css','utf8'),await readFile(new URL('./next-chapter.css',import.meta.url),'utf8'),'Scoped CSS exactly matches permanent source');
console.log('PASS: deployed component and scoped CSS match permanent source');
